# ============================================================================================
# A1 — COMPLETENESS + NO SIXTH WAY over the whole shipped registry.
# ============================================================================================

class TestA1CompletenessNoSixthWay(unittest.TestCase):

    def setUp(self):
        self._s, self.gate, self.views = P4.build_full_kernel_for_census()
        self.rows = P4.census(self.gate, self.views)

    def test_census_is_over_the_whole_registry(self):
        # completeness = enumeration (P3): one row per registered op, no more, no fewer.
        self.assertEqual(len(self.rows), len(self.gate.ops))
        self.assertEqual(sorted(r["op"] for r in self.rows), sorted(self.gate.ops))

    def test_every_op_reads_as_one_family_or_not_a_path(self):
        allowed = set(P4.FIVE_FAMILIES) | {"not-a-path", "sixth-way", "unknown"}
        for r in self.rows:
            self.assertIn(r["class"], allowed, "%s got an out-of-vocabulary class %r" % (r["op"], r["class"]))
            self.assertTrue(r["reason"], "%s carries no reason — every reading is recorded" % r["op"])

    def test_no_sixth_way(self):
        # THE load-bearing invariant: no op moves information across a boundary while fitting no
        # family. A non-empty set is I20 refuted — a paper finding, never a silent family-widening.
        sw = P4.sixth_way_rows(self.rows)
        self.assertEqual(sw, [], "a SIXTH WAY exists — an op moves bytes but fits no family: %s"
                         % [(r["op"], r["reason"]) for r in sw])

    def test_no_unknown(self):
        # every op's source was read; an unreadable op would RED here rather than hide as
        # not-a-path (precision 2).
        uk = P4.unknown_rows(self.rows)
        self.assertEqual(uk, [], "an op's source could not be read: %s" % [r["op"] for r in uk])

    def test_every_family_is_populated(self):
        # the families are not empty categories — each has real members over the shipped registry
        # (design/52 §7 P4 premise). An empty family would mean the census proves nothing about it.
        for family in P4.FIVE_FAMILIES:
            self.assertTrue(P4.family_rows(self.rows, family),
                            "family %r has no members over the shipped registry" % family)


