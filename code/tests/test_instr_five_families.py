# every op reads as one of five families or as not-a-path, and the census REDS on an op that moves
# information across a boundary yet fits no family. Full declaration: SCOPE-STATEMENT.md.
"""P4 · I20 [GREEN] — THE FIVE-FAMILIES CENSUS.

Three proofs, one instrument (the sibling of the effect-order census):

  A1  COMPLETENESS + NO SIXTH WAY — every op registered on the gate is classified; the census is
      over the WHOLE registry (len(rows) == len(gate.ops)); the `sixth-way` set (a byte-mover
      fitting no family) is EMPTY; the `unknown` set (an op whose source will not read) is EMPTY.
  A2  READING MATCHES COMMITTED EVIDENCE — the live reading, rendered by the instrument's own
      `--md`, equals the committed evidence table byte-for-byte. A new op, or a changed reading,
      moves this table and REDS here until the evidence is regenerated (never hand-edited).
  A3  THE CHECK CAN FAIL (positive control) — a PLANTED op that moves bytes by a primitive
      belonging to no family reads as `sixth-way` and REDS; with the plant removed the census is
      green. Two controls: a STATIC one (classify a planted op directly) and a BEHAVIOURAL one (a
      planted op registered on a real gate, flagged by the census, then removed).
"""

