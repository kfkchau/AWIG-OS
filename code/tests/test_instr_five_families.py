# ============================================================================================
# A3 — the check can fail: a planted byte-mover fitting no family reads as sixth-way.
# ============================================================================================

# A planted handler that moves bytes by a byte-transfer primitive (hand_off) — a real crossing —
# under an op NAME and LAW that match NO family. This is the shape the census exists to catch.
PLANT_SIXTH_WAY_SOURCE = '''\
def _sixth_way_plant(actor, params):
    # a real byte crossing (a content datum handed to a receiver) under no recognised conduit.
    hand_off([params["target_hash"]], params["receipt"])
    return {"actor": actor, "action": "SIXTH-WAY-PLANT", "object": params["target_hash"],
            "rule_cited": "NONE"}
'''


class TestA3PlantedSixthWayStatic(unittest.TestCase):

    def test_classifier_flags_a_byte_mover_with_no_family_as_sixth_way(self):
        # read the planted op directly: no definition (code-registered shape), a handler that
        # moves bytes, a name in no family -> sixth-way.
        row = P4.classify("SIXTH-WAY-PLANT", definition=None,
                          handler_src=PLANT_SIXTH_WAY_SOURCE, law="NONE")
        self.assertEqual(row["class"], "sixth-way",
                         "the classifier did not flag a byte-mover fitting no family — the census cannot fail")
        self.assertIn("across a boundary", row["reason"])

    def test_a_definition_born_byte_mover_with_no_family_is_a_sixth_way(self):
        # the other shape: a definition-born op carrying content_params to a target_param under a
        # name/law in no family -> sixth-way. (Not registered — no founding move; read directly.)
        plant_def = {"law_cited": "NONE", "content_params": {"payload": "payload_hash"},
                     "target_param": "receiver"}
        row = P4.classify("BEAM-CONTENT", definition=plant_def, handler_src=None, law="NONE")
        self.assertEqual(row["class"], "sixth-way")

    def test_a_real_family_member_is_not_flagged(self):
        # the control the other way: a real byte-mover that IS in a family (COMMS-SEND, channels)
        # is NOT a sixth way — the plant is discriminating, not a check that reds on everything.
        _s, gate, views = P4.build_full_kernel_for_census()
        rows = P4.census(gate, views)
        by_op = {r["op"]: r for r in rows}
        self.assertEqual(by_op["COMMS-SEND"]["class"], "channels")
        self.assertEqual(by_op["HANDOVER-CUSTODY"]["class"], "custody-handover")


class TestA3PlantedSixthWayBehavioural(unittest.TestCase):

    def _register_plant(self, gate):
        """Register (in memory, NOT a founding CREATE-OP) a byte-moving op that fits no family —
        the exact shape the census exists to catch. gate.register is a live registration, like the
        effect-order census's planted-inline control; nothing is written to the pack."""
        def _sixth_way_plant(actor, params):
            hand_off([params["target_hash"]], params["receipt"])          # noqa: F821 — planted crossing
            return {"actor": actor, "action": "SIXTH-WAY-PLANT",
                    "object": params["target_hash"], "rule_cited": "NONE"}
        gate.register("SIXTH-WAY-PLANT",
                      {"description": "planted byte-mover fitting no family",
                       "rules": [], "params": {"target_hash": "required", "receipt": "required"}},
                      _sixth_way_plant)

    def test_planted_op_reds_the_census_then_greens_on_removal(self):
        _s, gate, views = P4.build_full_kernel_for_census()

        # green before the plant
        self.assertEqual(P4.sixth_way_rows(P4.census(gate, views)), [])

        # THE POSITIVE FIRES: the plant is present and reads as a sixth way.
        self._register_plant(gate)
        rows = P4.census(gate, views)
        sw = [r["op"] for r in P4.sixth_way_rows(rows)]
        self.assertIn("SIXTH-WAY-PLANT", sw,
                      "the planted byte-mover was NOT flagged sixth-way — the positive control did "
                      "not fire, so this test proves nothing")
        self.assertEqual(len(rows), len(gate.ops))          # still complete WITH the plant

        # remove the plant: the census is green again — the finding class is kept, not defeated.
        gate.unregister("SIXTH-WAY-PLANT")
        self.assertEqual(P4.sixth_way_rows(P4.census(gate, views)), [])


